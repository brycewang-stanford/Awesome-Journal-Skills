#!/usr/bin/env python3
"""Vendor the shared resources each pack links to into that pack, so installs work.

``claude plugin install`` copies only the plugin's own directory into the plugin
cache. Every skill link of the form ``../../../shared-resources/...`` therefore pointed
at nothing for an installed user — 489 links to the execution manual alone, and every
link the Research Toolkit's pre-submission skills make. This was confirmed with a clean
install into an isolated config directory on 2026-11-23.

The fix is the one the packs already use for their code library: a byte-identical copy
inside the pack, regenerated from the single source of truth.

* Shared material is grouped into **bundles** (a ``shared-resources/`` subdirectory's
  prose + small tools). A pack receives a bundle when any of its Markdown links into it.
  It lands at ``<Pack>/resources/shared/<bundle>/`` with the source's own layout, so
  links between files of the same bundle keep working unchanged.
* Links that leave the bundle (to another bundle, to ``tools/``, to a TSV, to another
  pack) become absolute GitHub URLs, so every copy of a file is identical whatever pack
  holds it — git stores one blob however many packs carry it.
* The pack's own links are rewritten to the vendored copy.
* The Research Toolkit additionally receives ``resources/preflight/`` — ``preflight.py``
  and the compiled ``venue-rules.json`` — so the deterministic preflight runs from a plain
  plugin install with no clone.

    python3 tools/vendor_shared.py --check   # exit 1 if any copy or link is stale (CI)
    python3 tools/vendor_shared.py --write   # regenerate

Edit the originals under ``shared-resources/`` (or ``tools/preflight.py``), never the
copies; ``--check`` in ``run_checks.py`` fails until the copies are regenerated.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

from venue_lib import ROOT

SHARED = ROOT / "shared-resources"
GITHUB = "https://github.com/brycewang-stanford/Awesome-Journal-Skills"
TOOLKIT = ROOT / "Research-Toolkit-Skills"

BUNDLES: dict[str, list[str]] = {
    "empirical-methods": [
        "README.md", "execution-with-mcp.md", "replication-package.md", "reporting-standards.md",
        "reviewer-objection-checklist.md", "worked-examples/dml-walkthrough.md",
        "worked-examples/iv-walkthrough.md", "worked-examples/rdd-walkthrough.md",
        "worked-examples/synthetic-control-walkthrough.md",
    ],
    "ml-conference-methods": [
        "README.md", "experiment-matrix.md", "reproducibility-artifact-checklist.md",
        "code/check_repro_package.py",
    ],
    "econometrics-methods": [
        "README.md", "simulation-and-replication-checklist.md", "code/check_simulation_package.py",
    ],
    "submission-readiness": [
        "README.md", "readiness-checklist.md", "simulated-referee.md", "response-to-referees.md",
        "worked-example-referee-report.md", "review-forms.md", "prose-polish.md",
        "cover-letter-and-disclosures.md",
    ],
    "journal-selection": [
        "README.md", "journal-match.md", "paper-profile.md", "worked-example.md",
        "eval/README.md", "eval/RESULTS.md",
    ],
}
TOOLKIT_EXTRA = {
    "resources/preflight/preflight.py": ROOT / "tools" / "preflight.py",
    "resources/preflight/venue-rules.json": SHARED / "submission-readiness" / "venue-rules.json",
}

LINK = re.compile(r"(\]\()([^)\s]+)((?:\s+\"[^\"]*\")?\))")
MD_HEADER = ("<!-- Vendored copy of {src} — generated by tools/vendor_shared.py. "
             "Edit the original and run `python3 tools/vendor_shared.py --write`. -->\n\n")
PY_HEADER = "# Vendored copy of {src} — generated by tools/vendor_shared.py; edit the original.\n"


def bundle_files(name: str) -> list[str]:
    return [f for f in BUNDLES[name] if (SHARED / name / f).exists()]


def packs() -> list[Path]:
    return sorted(p.parent.parent for p in ROOT.glob("*/.claude-plugin/plugin.json"))


def github_url(target: Path) -> str:
    rel = target.relative_to(ROOT).as_posix()
    return f"{GITHUB}/{'tree' if target.is_dir() else 'blob'}/main/{rel}"


def split_target(raw: str) -> tuple[str, str]:
    path, sep, frag = raw.partition("#")
    return path, (sep + frag)


def is_external(raw: str) -> bool:
    return raw.startswith(("http://", "https://", "mailto:", "data:", "#", "<"))


def which_bundle(resolved: Path, pack: Path | None) -> tuple[str, str] | None:
    """(bundle, rel) when ``resolved`` is a shared file or its vendored copy in ``pack``."""
    for base in [SHARED] + ([pack / "resources" / "shared"] if pack else []):
        try:
            rel = resolved.relative_to(base).as_posix()
        except ValueError:
            continue
        name, _, rest = rel.partition("/")
        if name in BUNDLES:
            return name, rest
    return None


def vendored_text(bundle: str, rel: str) -> str:
    src = SHARED / bundle / rel
    text = src.read_text(encoding="utf-8")
    src_rel = src.relative_to(ROOT).as_posix()
    if src.suffix == ".py":
        lines = text.split("\n", 1)
        if lines[0].startswith("#!"):
            return lines[0] + "\n" + PY_HEADER.format(src=src_rel) + (lines[1] if len(lines) > 1 else "")
        return PY_HEADER.format(src=src_rel) + text
    if src.suffix != ".md":
        return text
    members = set(bundle_files(bundle))

    def sub(m: re.Match) -> str:
        raw = m.group(2)
        if is_external(raw):
            return m.group(0)
        path, frag = split_target(raw)
        if not path:
            return m.group(0)
        resolved = (src.parent / path).resolve()
        try:
            rel_to_bundle = resolved.relative_to(SHARED / bundle).as_posix()
        except ValueError:
            rel_to_bundle = None
        if rel_to_bundle in members:
            return m.group(0)
        if not resolved.exists():
            return m.group(0)
        try:
            resolved.relative_to(ROOT)
        except ValueError:
            return m.group(0)
        return m.group(1) + github_url(resolved) + frag + m.group(3)

    return MD_HEADER.format(src=src_rel) + LINK.sub(sub, text)


def pack_markdown(pack: Path) -> list[Path]:
    shared = pack / "resources" / "shared"
    return sorted(p for p in pack.rglob("*.md") if shared not in p.parents)


def rewrite_pack_links(pack: Path, md: Path, text: str, needed: set[str]) -> str:
    def sub(m: re.Match) -> str:
        raw = m.group(2)
        if is_external(raw):
            return m.group(0)
        path, frag = split_target(raw)
        if not path:
            return m.group(0)
        resolved = (md.parent / path).resolve()
        hit = which_bundle(resolved, pack)
        if not hit:
            return m.group(0)
        bundle, rel = hit
        if rel in bundle_files(bundle):
            needed.add(bundle)  # only a link into a vendored file needs the copy
            dest = pack / "resources" / "shared" / bundle / rel
            new = os.path.relpath(dest, md.parent).replace(os.sep, "/")
        else:
            original = SHARED / bundle / rel if rel else SHARED / bundle
            if not original.exists():
                return m.group(0)
            new = github_url(original)
        return m.group(1) + new + frag + m.group(3)

    return LINK.sub(sub, text)


def plan() -> tuple[dict[Path, str], list[Path]]:
    """(files to write with their expected content, stale vendored files to delete)."""
    expected: dict[Path, str] = {}
    for pack in packs():
        needed: set[str] = set()
        for md in pack_markdown(pack):
            text = md.read_text(encoding="utf-8")
            new = rewrite_pack_links(pack, md, text, needed)
            if new != text:
                expected[md] = new
        if pack == TOOLKIT:
            needed.add("submission-readiness")
        for bundle in sorted(needed):
            for rel in bundle_files(bundle):
                expected[pack / "resources" / "shared" / bundle / rel] = vendored_text(bundle, rel)
        if pack == TOOLKIT:
            for dest, src in TOOLKIT_EXTRA.items():
                if src.exists():
                    text = src.read_text(encoding="utf-8")
                    if src.suffix == ".py":
                        head, _, rest = text.partition("\n")
                        text = head + "\n" + PY_HEADER.format(src=src.relative_to(ROOT).as_posix()) + rest
                    expected[pack / dest] = text
    managed = {p for p in expected if "resources/shared/" in p.as_posix() or "resources/preflight/" in p.as_posix()}
    stale = []
    for pack in packs():
        for sub in ("resources/shared", "resources/preflight"):
            d = pack / sub
            if d.exists():
                stale += [p for p in d.rglob("*") if p.is_file() and p not in managed]
    return expected, stale


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    expected, stale = plan()
    changed = [p for p, t in expected.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
    if args.write:
        for p in changed:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(expected[p], encoding="utf-8")
        for p in stale:
            p.unlink()
        n_vendored = sum(1 for p in expected if "resources/shared/" in p.as_posix())
        print(f"vendor_shared: wrote {len(changed)} file(s), removed {len(stale)} stale; "
              f"{n_vendored} vendored copies across {len(packs())} packs")
        return 0
    if changed or stale:
        for p in (changed + stale)[:15]:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        print(f"ERROR: {len(changed)} vendored file(s)/link(s) out of date, {len(stale)} stale copies; "
              "run python3 tools/vendor_shared.py --write", file=sys.stderr)
        return 1
    print(f"OK: vendored shared resources current ({len(expected)} managed files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
